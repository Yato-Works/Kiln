"""Deterministic harness generation for ``kiln link`` (Phase 4).

``kiln build`` writes a translation unit; ``kiln link`` has to *execute* it.  The
harness is generated rather than hand written so that the test vectors are
reviewable Python and the C is a pure function of the length:

* five byte patterns -- zeros, an alternating 0x00/0xFF pattern, both uniform
  extremes and a 7-byte ramp -- each an adversarial input for a fixed-point
  network (uniform extremes drive saturation, alternating bytes drive the max
  pool's tie-breaking, the ramp spreads over the whole quantisation range);
* one ``printf("%d %d\\n", vector, prediction)`` line per vector, which the
  Python side parses back and compares against ``kiln.ref``.

Because every vector is a pure function of the input length, a given spec always
links the same image and replays the same inputs: the harness inherits Kiln's
determinism rule instead of re-mixing randomness into the verification.
"""

from __future__ import annotations

from pathlib import Path
from typing import Sequence

from ..ir.kir import DType

__all__ = (
    "VECTOR_NAMES",
    "harness_vectors",
    "parse_predictions",
    "render_harness",
    "to_input_domain",
)

#: Names of ``harness_vectors``' rows, in order (used by the link report).
VECTOR_NAMES: tuple[str, ...] = ("zeros", "alternating", "high", "low", "ramp")


def harness_vectors(input_len: int) -> tuple[tuple[int, ...], ...]:
    """The fixed byte patterns the generated harness replays, as raw bytes."""
    if input_len <= 0:
        raise ValueError(f"harness input length must be positive, got {input_len}")
    return (
        tuple(0x00 for _ in range(input_len)),
        tuple(0x00 if index % 2 == 0 else 0xFF for index in range(input_len)),
        tuple(0xFF for _ in range(input_len)),
        tuple(0x80 for _ in range(input_len)),
        tuple((index * 7 + 1) % 256 for index in range(input_len)),
    )


def to_input_domain(dtype: DType, vector: Sequence[int]) -> list[int]:
    """The reference-side values for one harness byte vector.

    The C entry point always takes ``const uint8_t *``; an ``int8`` graph input
    reinterprets those bytes two's-complement, so the Python oracle has to see
    the same signed values.
    """
    if dtype is DType.UINT8:
        return [int(byte) & 0xFF for byte in vector]
    return [int(byte) - 256 if byte > 127 else int(byte) for byte in vector]


def render_harness(input_len: int, vectors: Sequence[Sequence[int]] = ()) -> str:
    """Renders the ``main()`` that replays ``vectors`` through the linked model."""
    rows = tuple(vectors) or harness_vectors(input_len)
    if not rows:
        raise ValueError("a harness needs at least one vector")
    for vector in rows:
        if len(vector) != input_len:
            raise ValueError(
                f"harness vector has {len(vector)} elements, expected {input_len}"
            )
    table = ",\n".join(
        "    {" + ", ".join(f"0x{byte & 0xFF:02X}" for byte in vector) + "}"
        for vector in rows
    )
    return f"""/* Generated by `kiln link`: replays fixed vectors through the linked model. */
#include <stdint.h>
#include <stdio.h>

int8_t kiln_predict(const uint8_t *input_bytes, int len);

static const uint8_t k_vectors[{len(rows)}][{input_len}] = {{
{table},
}};

int main(void) {{
    for (int vector = 0; vector < {len(rows)}; ++vector) {{
        printf("%d %d\\n", vector, (int)kiln_predict(k_vectors[vector], {input_len}));
    }}
    return 0;
}}
"""


def parse_predictions(stdout: str, *, expected: int) -> tuple[int, ...]:
    """Reads the harness' ``index prediction`` lines back, in index order."""
    seen: dict[int, int] = {}
    for line in stdout.splitlines():
        parts = line.split()
        if len(parts) != 2:
            continue
        try:
            index, prediction = int(parts[0]), int(parts[1])
        except ValueError:
            continue
        seen[index] = prediction
    missing = [index for index in range(expected) if index not in seen]
    if missing:
        raise ValueError(f"harness output is missing vector(s) {missing}: {stdout!r}")
    return tuple(seen[index] for index in range(expected))


def harness_source_path(out_dir: Path) -> Path:
    """Where the generated harness lives inside an output directory."""
    return out_dir / "harness.c"
