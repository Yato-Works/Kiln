"""Small freestanding runtimes used by truthful system-emulator targets."""

from __future__ import annotations

__all__ = ("CORTEX_M_LINKER_SCRIPT", "CORTEX_M_SEMIHOST_ASM", "CORTEX_M_STARTUP_C")


CORTEX_M_LINKER_SCRIPT = r"""/* Generated by Kiln for a Cortex-M system-emulator image. */
ENTRY(Reset_Handler)

MEMORY
{
    FLASH (rx)  : ORIGIN = 0x00000000, LENGTH = 4M
    RAM   (rwx) : ORIGIN = 0x20000000, LENGTH = 4M
}

SECTIONS
{
    .isr_vector :
    {
        . = ALIGN(4);
        KEEP(*(.isr_vector))
        . = ALIGN(4);
    } > FLASH

    .text :
    {
        . = ALIGN(4);
        *(.text*)
        *(.rodata*)
        . = ALIGN(4);
    } > FLASH

    .data : AT(LOADADDR(.text) + SIZEOF(.text))
    {
        . = ALIGN(4);
        _sdata = .;
        *(.data*)
        . = ALIGN(4);
        _edata = .;
    } > RAM
    _sidata = LOADADDR(.data);

    .bss (NOLOAD) :
    {
        . = ALIGN(4);
        _sbss = .;
        *(.bss*)
        *(COMMON)
        . = ALIGN(4);
        _ebss = .;
    } > RAM

    . = ALIGN(8);
    _stack_top = ORIGIN(RAM) + LENGTH(RAM);
}
"""


CORTEX_M_STARTUP_C = r"""/* Generated by Kiln: minimal Cortex-M reset and data initialization. */
#include <stddef.h>
#include <stdint.h>

extern int main(void);
extern unsigned char _stack_top[];
extern unsigned char _sidata[];
extern unsigned char _sdata[];
extern unsigned char _edata[];
extern unsigned char _sbss[];
extern unsigned char _ebss[];
extern void kiln_semihost_call(uint32_t operation, const void *argument);

/* The QEMU target is freestanding: provide the small libc surface that
 * generated frontends may use without linking a hosted runtime. */
void *memcpy(void *destination, const void *source, size_t count) {
    unsigned char *out = destination;
    const unsigned char *in = source;
    while (count-- > 0) {
        *out++ = *in++;
    }
    return destination;
}

void *memset(void *destination, int value, size_t count) {
    unsigned char *out = destination;
    while (count-- > 0) {
        *out++ = (unsigned char)value;
    }
    return destination;
}

void Reset_Handler(void) __attribute__((noreturn));

void Reset_Handler(void) {
    unsigned char *source = _sidata;
    unsigned char *destination = _sdata;
    while (destination < _edata) {
        *destination++ = *source++;
    }
    destination = _sbss;
    while (destination < _ebss) {
        *destination++ = 0;
    }
    (void)main();
    for (;;) {
    }
}

void abort(void) __attribute__((noreturn));

void abort(void) {
    uint32_t reason = 0x20023u;
    kiln_semihost_call(0x18u, &reason);
    for (;;) {
    }
}

__attribute__((section(".isr_vector"), used))
const uintptr_t kiln_vector_table[2] = {
    (uintptr_t)_stack_top,
    (uintptr_t)&Reset_Handler,
};
"""


CORTEX_M_SEMIHOST_ASM = r"""/* Generated by Kiln: ARM semihosting call gate. */
.syntax unified
.thumb
.text
.global kiln_semihost_call
.type kiln_semihost_call, %function
kiln_semihost_call:
    bkpt 0xAB
    bx lr
.size kiln_semihost_call, .-kiln_semihost_call
"""
