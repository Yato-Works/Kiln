"""Reproducible table generation for the KWS fixed-point frontend.

The generated header contains only static constants. Keeping this generator
separate makes the numerical contract auditable without deployment-time
NumPy or PyTorch dependencies.
"""
from __future__ import annotations

import math
import struct
from pathlib import Path

SAMPLE_RATE = 16000
N_FFT = 1024
WIN_LEN = 640
HOP_LEN = 320
N_MELS = 10
N_FRAMES = 49
Q15 = 32767
Q16 = 65536


def _fmt(values: list[int], width: int = 12) -> str:
    lines = []
    for start in range(0, len(values), width):
        lines.append("    " + ", ".join(str(v) for v in values[start : start + width]) + ",")
    return "\n".join(lines)


def _mel_table() -> tuple[list[int], list[int], list[int]]:
    mel_min = 2595.0 * math.log10(1.0 + 20.0 / 700.0)
    mel_max = 2595.0 * math.log10(1.0 + 4000.0 / 700.0)
    hz = [700.0 * (10.0 ** ((mel_min + (mel_max - mel_min) * i / (N_MELS + 1)) / 2595.0) - 1.0) for i in range(N_MELS + 2)]
    bins = [int(round(h * N_FFT / SAMPLE_RATE)) for h in hz]
    starts: list[int] = []
    lengths: list[int] = []
    weights: list[int] = []
    for i in range(N_MELS):
        left, center, right = bins[i : i + 3]
        w = [0] * (right - left)
        for k in range(left, center):
            w[k - left] = round(((k - left) / (center - left)) * Q15)
        for k in range(center, right):
            w[k - left] = round(((right - k) / (right - center)) * Q15)
        starts.append(left)
        lengths.append(len(w))
        weights.extend(w)
    return starts, lengths, weights


def generate() -> str:
    hann = [round(0.5 * (1.0 - math.cos(2.0 * math.pi * i / WIN_LEN)) * Q15) for i in range(WIN_LEN)]
    bit_reverse = [int(f"{i:010b}"[::-1], 2) for i in range(N_FFT)]
    cos = [round(math.cos(-2.0 * math.pi * i / N_FFT) * Q15) for i in range(N_FFT // 2)]
    sin = [round(math.sin(-2.0 * math.pi * i / N_FFT) * Q15) for i in range(N_FFT // 2)]
    log2 = [round(math.log2(1.0 + i / 64.0) * Q16) for i in range(64)]
    starts, lengths, weights = _mel_table()
    return f'''/* Generated by examples/kws/frontend/gen_tables.py. */
#ifndef KWS_TABLES_H
#define KWS_TABLES_H
#include <stdint.h>
#define KWS_SAMPLE_RATE {SAMPLE_RATE}
#define KWS_WIN_LEN {WIN_LEN}
#define KWS_HOP_LEN {HOP_LEN}
#define KWS_FFT_SIZE {N_FFT}
#define KWS_N_MELS {N_MELS}
#define KWS_N_FRAMES {N_FRAMES}
static const int16_t kws_hann_window[KWS_WIN_LEN] = {{
{_fmt(hann)}
}};
static const int16_t kws_bit_reverse[KWS_FFT_SIZE] = {{
{_fmt(bit_reverse)}
}};
static const int16_t kws_twiddle_cos[KWS_FFT_SIZE / 2] = {{
{_fmt(cos)}
}};
static const int16_t kws_twiddle_sin[KWS_FFT_SIZE / 2] = {{
{_fmt(sin)}
}};
static const uint16_t kws_mel_start_bin[KWS_N_MELS] = {{
{_fmt(starts)}
}};
static const uint16_t kws_mel_filter_len[KWS_N_MELS] = {{
{_fmt(lengths)}
}};
static const int16_t kws_mel_weights[{len(weights)}] = {{
{_fmt(weights)}
}};
static const uint16_t kws_log2_lut[64] = {{
{_fmt(log2)}
}};
#endif
'''


if __name__ == "__main__":
    Path(__file__).with_name("kws_tables.h").write_text(generate(), encoding="utf-8")
